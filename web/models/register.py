"""Writes the hundred-risk register model: web/models/register.yaml with
the demo's placeholders, and examples/register.yaml with their defaults
filled in. Deterministic; run from the repository root."""

import random

CATEGORIES = [
    ("cyber", 14), ("operations", 14), ("supply", 12), ("legal", 12),
    ("safety", 12), ("financial", 12), ("facilities", 12), ("people", 12),
]
DEFAULTS = {"control": 0.3, "cap": 10000000}


def risks():
    rng = random.Random(2026)
    out = []
    for category, n in CATEGORIES:
        for i in range(1, n + 1):
            mean = round(10 ** rng.uniform(-1.5, 0.3), 3)          # events per year
            sd = round(mean * rng.uniform(0.3, 1.0), 3)
            median = round(10 ** rng.uniform(3.7, 6.5), -2)         # loss per event
            p90 = round(median * rng.uniform(2.5, 4), -2)
            out.append((f"{category}_{i:02d}", category, mean, sd, median, p90))
    return out


def model(control, cap):
    # The exact curve at a thousandth needs a grid of millions of points
    # for a hundred heavy-tailed risks; at a hundredth it closes at half a
    # million in about a minute natively.
    lines = ["period: { days: 365 }", "transform_tol: 0.01", "graphs:", "  - id: register", "    sources:"]
    for rid, _, mean, sd, _, _ in risks():
        lines.append(f"      - {{ id: {rid}, frequency: {{ gamma: {{ mean: {mean}, sd: {sd} }} }}, to: {rid}_screen }}")
    lines.append("    nodes:")
    lines.append("      - id: stopped")
    for rid, category, _, _, median, p90 in risks():
        lines.append(f"      - {{ id: {rid}_screen, outcomes: [ {{ to: stopped, p: {control} }}, {{ to: {rid}_loss }} ] }}")
        lines.append(f"      - {{ id: {rid}_loss, functions: [ {{ name: loss, category: {category}, lognormal: {{ median: {median}, p90: {p90} }}, cap: {cap} }} ] }}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    with open("web/models/register.yaml", "w") as f:
        f.write("# Generated by register.py; edit that, not this.\n")
        f.write(model("{{control}}", "{{cap}}"))
    with open("examples/register.yaml", "w") as f:
        f.write("# A register of a hundred risks, each an event rate and a loss per\n"
                "# event, with a control that stops a share of events and a cap on any\n"
                "# one loss. The exceedance curve of the period total is the cumulative\n"
                "# risk profile; the breakdown by source ranks the risks by expected\n"
                "# loss. Every rate is a gamma, so the exact distribution is closed\n"
                "# form and the curve comes with bounds in about a second.\n"
                "# Generated by web/models/register.py; edit that, not this.\n")
        f.write(model(DEFAULTS["control"], DEFAULTS["cap"]))
